//! Per-file artefact cache for the new single-pass `media_analyze` pipeline.
//!
//! Layout (under `{storage_root}/media_cache/{file_id}/`):
//!
//! ```text
//! /data/media_cache/<file_id>/
//!     vhash.bin              -- 256 B descriptors @ 3 fps
//!     chromaprint.bin        -- raw u32 fingerprint, full file
//!     silence.json           -- [{start_s, end_s, duration_s}]
//!     black_frames.json      -- [{start_s, end_s, duration_s}]
//!     loudness.json          -- {integrated_lufs}
//!     audio_peaks.bin        -- version:1, pps:1, (min_i8, max_i8) pairs
//!     embeddings.bin         -- fp16 1152-dim per JPEG, L2-normalised
//!     source.tmp             -- ephemeral: deleted after analyze + NAS copy confirmed
//!     manifest.json
//! ```
//!
//! Trickplay sprites stay under `{storage_root}/thumbnails/<file_id>/`; the
//! manifest references that path explicitly via `trickplay_dir`.
//!
//! All sidecar writes go through `writers::write_atomic` which writes to a
//! sibling `.tmp` file and renames in one shot, so a crashed analyze never
//! leaves a half-written sidecar visible to the legacy code path.

use std::path::{Path, PathBuf};

use uuid::Uuid;

pub mod analyze;
pub mod embeddings;
pub mod episode_cache;
pub mod integrity;
pub mod picture_area;
pub mod readers;
pub mod trickplay_sink;
pub mod writers;

/// Current pipeline version. Bump when the on-disk format or the meaning of a
/// branch's bytes changes — the manifest carries this and the backfill walker
/// uses it to find files needing regeneration.
///
/// History:
/// - v1: initial single-pass pipeline (trickplay, vhash, chromaprint, silence,
///   loudness, audio_peaks, embeddings).
/// - v2: adds `black_frames.json` so boundary refinement in skip_detect
///   can run fully from cache.
pub const PIPELINE_VERSION: i32 = 2;

/// Lowest pipeline_version that the readers + cross-episode detector accept
/// from a persisted episode_cache manifest. Bump in lockstep with breaking
/// format changes. Older persisted artefacts are treated as missing and
/// regenerated by the next analyze.
pub const MIN_SUPPORTED_PIPELINE_VERSION: i32 = 2;

/// Branch IDs in the manifest. These are the same conceptual branches as
/// `kob_ffmpeg::single_pass::BranchId` but live in the cache, so they get
/// their own enum to avoid coupling cache layout to the ffmpeg crate.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Branch {
    Trickplay,
    Vhash,
    Chromaprint,
    Silence,
    Loudness,
    AudioPeaks,
    Embeddings,
    BlackFrames,
}

impl Branch {
    pub fn as_str(self) -> &'static str {
        match self {
            Branch::Trickplay => "trickplay",
            Branch::Vhash => "vhash",
            Branch::Chromaprint => "chromaprint",
            Branch::Silence => "silence",
            Branch::Loudness => "loudness",
            Branch::AudioPeaks => "audio_peaks",
            Branch::Embeddings => "embeddings",
            Branch::BlackFrames => "black_frames",
        }
    }
}

/// Resolve the cache directory for a file_id under `{storage_root}/media_cache/<file_id>/`.
pub fn cache_dir(storage_root: &str, file_id: Uuid) -> PathBuf {
    PathBuf::from(storage_root)
        .join("media_cache")
        .join(file_id.to_string())
}

/// Trickplay sprites stay at `{storage_root}/thumbnails/<file_id>/`.
pub fn trickplay_dir(storage_root: &str, file_id: Uuid) -> PathBuf {
    PathBuf::from(storage_root)
        .join("thumbnails")
        .join(file_id.to_string())
}

/// Filename for a branch's sidecar inside a cache directory. Returns `None`
/// for `Branch::Trickplay` because trickplay is a directory of sprite JPEGs,
/// not a single file.
pub fn sidecar_filename(branch: Branch) -> Option<&'static str> {
    match branch {
        Branch::Trickplay => None,
        Branch::Vhash => Some("vhash.bin"),
        Branch::Chromaprint => Some("chromaprint.bin"),
        Branch::Silence => Some("silence.json"),
        Branch::Loudness => Some("loudness.json"),
        Branch::AudioPeaks => Some("audio_peaks.bin"),
        Branch::Embeddings => Some("embeddings.bin"),
        Branch::BlackFrames => Some("black_frames.json"),
    }
}

/// Path to a per-file sidecar within the cache dir. Branch determines filename.
pub fn sidecar_path(storage_root: &str, file_id: Uuid, branch: Branch) -> PathBuf {
    match branch {
        Branch::Trickplay => trickplay_dir(storage_root, file_id),
        other => cache_dir(storage_root, file_id)
            .join(sidecar_filename(other).expect("non-trickplay branches have filenames")),
    }
}

/// The local-spool target written by the dual-write tee at ingest time
/// (Phase 5+). `media_analyze` prefers this when it exists; otherwise it
/// reads from the media_root path directly.
pub fn source_spool_path(storage_root: &str, file_id: Uuid) -> PathBuf {
    cache_dir(storage_root, file_id).join("source.tmp")
}

/// Path to the manifest JSON at the cache dir root.
pub fn manifest_path(storage_root: &str, file_id: Uuid) -> PathBuf {
    cache_dir(storage_root, file_id).join("manifest.json")
}

/// True if a sidecar file exists on disk. Doesn't validate contents — use
/// `readers::read_manifest` for the authoritative "is this branch usable".
pub fn sidecar_exists(storage_root: &str, file_id: Uuid, branch: Branch) -> bool {
    let path = sidecar_path(storage_root, file_id, branch);
    if branch == Branch::Trickplay {
        // Trickplay is a directory — consider present if it exists with any *.jpg.
        path.is_dir()
            && std::fs::read_dir(&path)
                .map(|mut it| {
                    it.any(|e| {
                        e.ok()
                            .and_then(|d| d.path().extension().map(|x| x == "jpg"))
                            .unwrap_or(false)
                    })
                })
                .unwrap_or(false)
    } else {
        path.is_file()
    }
}

/// Make the cache + embed_src directories for a file, if they don't already exist.
pub fn ensure_dirs(storage_root: &str, file_id: Uuid) -> std::io::Result<()> {
    std::fs::create_dir_all(cache_dir(storage_root, file_id))?;
    Ok(())
}

/// Drop the per-file `media_cache/{file_id}/` directory (audio_peaks +
/// source.tmp + the per-file manifest). Called by the same handlers that
/// remove `episode_cache/{namespace}/{id}/` when a file row is deleted, so
/// the file-bound cleanup is eager and complete. Best-effort — a missing
/// directory is not an error.
pub async fn remove_per_file(storage_root: &str, file_id: Uuid) -> std::io::Result<()> {
    match tokio::fs::remove_dir_all(cache_dir(storage_root, file_id)).await {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        other => other,
    }
}

/// Convenience: full path to a `parent`-relative path, or itself if absolute.
#[allow(dead_code)]
fn join_or_keep(parent: &Path, p: &Path) -> PathBuf {
    if p.is_absolute() {
        p.to_path_buf()
    } else {
        parent.join(p)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cache_paths_under_storage_root() {
        let id = Uuid::nil();
        assert_eq!(
            cache_dir("/data", id),
            PathBuf::from(format!("/data/media_cache/{id}"))
        );
        assert_eq!(
            sidecar_path("/data", id, Branch::Vhash),
            PathBuf::from(format!("/data/media_cache/{id}/vhash.bin"))
        );
        assert_eq!(
            sidecar_path("/data", id, Branch::Trickplay),
            PathBuf::from(format!("/data/thumbnails/{id}"))
        );
        assert_eq!(
            source_spool_path("/data", id),
            PathBuf::from(format!("/data/media_cache/{id}/source.tmp"))
        );
        assert_eq!(
            manifest_path("/data", id),
            PathBuf::from(format!("/data/media_cache/{id}/manifest.json"))
        );
    }

    #[test]
    fn join_or_keep_is_inert_for_absolute() {
        let abs = Path::new("/absolute/path");
        assert_eq!(join_or_keep(Path::new("/whatever"), abs), abs.to_path_buf());
        let rel = Path::new("relative.bin");
        assert_eq!(
            join_or_keep(Path::new("/parent"), rel),
            PathBuf::from("/parent/relative.bin")
        );
    }
}
