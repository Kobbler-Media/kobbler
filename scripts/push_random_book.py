#!/usr/bin/env python3
import argparse
import io
import json
import random
import uuid
import zipfile
import zlib
from datetime import datetime, timezone
from urllib import request

TITLES = [
    "Rust at Dawn",
    "Echoes of Kether",
    "The Glass Orchard",
    "Signal & Storm",
    "Atlas of Quiet",
    "Midnight Semaphore",
    "The Last Keystroke",
    "Copper Skyline",
]

AUTHORS = [
    "Ava Marshall",
    "Noah Sinclair",
    "Priya Patel",
    "Liam Carter",
    "Sofia Alvarez",
    "Eli Bennett",
    "Zara Quinn",
    "Mara Voss",
]

SERIES = [
    "Night Circuit",
    "Kobbler Tales",
    "Sable Archive",
    None,
]


def make_epub_bytes(title, author):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as zf:
        zf.writestr("mimetype", "application/epub+zip", compress_type=zipfile.ZIP_STORED)
        zf.writestr(
            "META-INF/container.xml",
            """<?xml version="1.0"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>""",
        )
        zf.writestr(
            "OEBPS/content.opf",
            f"""<?xml version="1.0"?>
<package version="2.0" xmlns="http://www.idpf.org/2007/opf" unique-identifier="BookId">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:title>{title}</dc:title>
    <dc:creator>{author}</dc:creator>
    <dc:language>en</dc:language>
    <dc:identifier id="BookId">urn:uuid:{uuid.uuid4()}</dc:identifier>
  </metadata>
  <manifest>
    <item id="content" href="content.xhtml" media-type="application/xhtml+xml"/>
  </manifest>
  <spine>
    <itemref idref="content"/>
  </spine>
</package>""",
        )
        zf.writestr(
            "OEBPS/content.xhtml",
            f"""<?xml version="1.0" encoding="utf-8"?>
<html xmlns="http://www.w3.org/1999/xhtml">
  <head><title>{title}</title></head>
  <body><h1>{title}</h1><p>By {author}</p></body>
</html>""",
        )
    return buffer.getvalue()


def _crc(chunk_type, data):
    return zlib.crc32(chunk_type + data) & 0xFFFFFFFF


def _png_chunk(chunk_type, data):
    length = len(data).to_bytes(4, "big")
    crc = _crc(chunk_type, data).to_bytes(4, "big")
    return length + chunk_type + data + crc


def make_cover_png(width=360, height=540, base=None):
    if base is None:
        base = random.randint(30, 90)
    rows = []
    for y in range(height):
        shade = base + int(110 * (y / max(height - 1, 1)))
        row = bytes([shade, min(255, shade + 20), min(255, shade + 40)] * width)
        rows.append(b"\x00" + row)
    raw = b"".join(rows)
    compressed = zlib.compress(raw, level=6)
    signature = b"\x89PNG\r\n\x1a\n"
    ihdr = width.to_bytes(4, "big") + height.to_bytes(4, "big") + b"\x08\x02\x00\x00\x00"
    return b"".join([
        signature,
        _png_chunk(b"IHDR", ihdr),
        _png_chunk(b"IDAT", compressed),
        _png_chunk(b"IEND", b""),
    ])


def api_call(method, url, token, body=None, content_type=None):
    headers = {
        "Authorization": f"Bearer {token}",
    }
    if content_type:
        headers["Content-Type"] = content_type
    data = body if body is not None else None
    req = request.Request(url, data=data, headers=headers, method=method)
    with request.urlopen(req) as resp:
        return resp.status, resp.read()


def main():
    parser = argparse.ArgumentParser(description="Push a random book into Kobbler.")
    parser.add_argument("--base-url", default="http://localhost:6766")
    parser.add_argument("--token", required=True, help="Kobbler ingest token")
    parser.add_argument("--format", default="KEPUB")
    parser.add_argument("--no-entitlement", action="store_true")
    args = parser.parse_args()

    title = random.choice(TITLES)
    author = random.choice(AUTHORS)
    series = random.choice(SERIES)
    series_index = float(random.randint(1, 6)) if series else None
    book_id = uuid.uuid4()

    pubdate = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    payload = {
        "title": title,
        "description": f"{title} is a demo book generated by Kobbler.",
        "language": "en",
        "publisher": "Kobbler Press",
        "pubdate": pubdate,
        "series_name": series,
        "series_index": series_index,
        "authors": [author],
    }

    base = args.base_url.rstrip("/")
    api_call(
        "PUT",
        f"{base}/api/v1/books/{book_id}",
        args.token,
        body=json.dumps(payload).encode("utf-8"),
        content_type="application/json",
    )

    cover = make_cover_png()
    api_call(
        "PUT",
        f"{base}/api/v1/books/{book_id}/cover",
        args.token,
        body=cover,
        content_type="image/png",
    )

    epub = make_epub_bytes(title, author)
    fmt = args.format.upper()
    api_call(
        "PUT",
        f"{base}/api/v1/books/{book_id}/files/{fmt}",
        args.token,
        body=epub,
        content_type="application/epub+zip",
    )

    if not args.no_entitlement:
        api_call(
            "POST",
            f"{base}/api/v1/entitlements",
            args.token,
            body=json.dumps({"book_id": str(book_id), "is_removed": False}).encode("utf-8"),
            content_type="application/json",
        )

    print("Created book:")
    print(f"- id: {book_id}")
    print(f"- title: {title}")
    print(f"- author: {author}")


if __name__ == "__main__":
    main()
