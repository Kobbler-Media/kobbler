#!/usr/bin/env bash
set -euo pipefail

root_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="${root_dir}/.env"
override_file="${root_dir}/docker-compose.override.yml"

ensure_env_key() {
    local key="$1" value="$2"
    if ! grep -q "^${key}=" "$env_file" || [[ -z "$(grep "^${key}=" "$env_file" | cut -d= -f2-)" ]]; then
        echo "${key}=${value}" >> "$env_file"
        echo "  Added ${key}"
    else
        echo "  ${key} is set"
    fi
}

echo "=== Kobbler Production Setup ==="
echo ""

# --- .env ---
if [[ -f "$env_file" ]]; then
    echo "Found existing .env"
    ensure_env_key "MEILI_MASTER_KEY" "$(openssl rand -hex 32)"
    ensure_env_key "NATS_TOKEN" "$(openssl rand -hex 32)"
else
    echo "Creating .env with defaults..."
    meili_key="$(openssl rand -hex 32)"
    nats_token="$(openssl rand -hex 32)"
    cat > "$env_file" <<EOF
# Kobbler production environment
# Generated by setup-prod.sh

MEILI_MASTER_KEY=${meili_key}
NATS_TOKEN=${nats_token}

# Uncomment/edit as needed:
# KOBBLER_API_PORT=6766
# KOBBLER_WEB_PORT=5173
# KOBBLER_PROXY_PORT=6767
# RUST_LOG=info,api=info,tower_http=info
EOF
    echo "  Created .env"
fi

echo ""

# --- docker-compose.override.yml for NATS exposure ---
if [[ -f "$override_file" ]]; then
    echo "docker-compose.override.yml already exists — skipping."
else
    read -rp "Will Kobload connect to this NATS instance? [y/N] " expose_nats
    if [[ "${expose_nats,,}" == "y" ]]; then
        nats_token="$(grep '^NATS_TOKEN=' "$env_file" | cut -d= -f2-)"
        cat > "$override_file" <<'EOF'
# Generated by setup-prod.sh — exposes NATS for external Kobload connection
services:
  nats:
    ports:
      - "${NATS_PORT:-4222}:4222"
EOF
        echo "  Created docker-compose.override.yml (NATS port 4222 exposed)"
        echo ""
        echo "  Kobload NATS_URL: nats://${nats_token}@<this-host>:4222"
        echo "  Use this URL when running setup-prod.sh on the Kobload server."
    else
        echo "  Skipped — NATS stays internal"
    fi
fi

echo ""
echo "Setup complete. Run:"
echo "  docker compose up -d --build"
